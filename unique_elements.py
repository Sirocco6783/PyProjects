# ============================================
# LAB: Удаление повторяющихся элементов из списка
# ============================================

# Исходный список с повторениями
my_list = [1, 2, 4, 4, 1, 4, 2, 6, 2, 9]

# Создаём новый пустой список для уникальных элементов
unique_list = []

# Перебираем все элементы исходного списка
for item in my_list:
    # Проверяем: если такого элемента ещё нет в unique_list,
    # то добавляем его
    if item not in unique_list:
        unique_list.append(item)

# Выводим результат
print("The list with unique elements only:")
print(unique_list)